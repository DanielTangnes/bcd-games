# Makes the clips of BCD's video test (tests/dxtests/video_test.c) and the header that carries them in the program
# (tests/dxtests/video_clips.h). Run by hand on a Mac when the clips change; the build (tools/build-dx-tests.sh) and CI use the
# tracked files and never run this. The clips are BCD's own: a synthetic picture and a sine wave made by
# tools/video-test-clips/genframes.py, no third-party media. They are small (about 18 KB and 26 KB):
#
#   test.mp4  H.264 Baseline (VideoToolbox, through AVAssetWriter: tools/video-test-clips/mkmp4.swift) and AAC-LC mono, 160x96,
#             30 frames at 15 fps, 44100 Hz, 2.0 s. macOS only (swiftc).
#   test.wmv  Windows Media Video 8 (wmv2) and Windows Media Audio 2 (wmav2) in an ASF file, the same pictures and tone. Made
#             with FFmpeg's own native encoders from the tarball the repository tracks for the app's FFmpeg
#             (build/ffmpeg/src/ffmpeg-7.1.1.tar.xz, SHA-256 checked, unmodified): a throw-away command-line build on the host
#             with only the encoders and the ASF muxer this needs, LGPL-2.1-or-later, configured --disable-gpl --disable-nonfree
#             --disable-version3. Set FFMPEG=<path> to use a build you already have.
#
# After it ran: tests/dxtests/clips/test.mp4, test.wmv and video_clips.h (the two files as C arrays plus their SHA-256).
# tests/host/check-bcd-tests.py checks the header against the files, the MP4's boxes (avcC Baseline, AAC esds, 30 samples) and
# the ASF file's header objects.
set -euo pipefail
R="$(cd "$(dirname "$0")/.." && pwd)"
T="$(mktemp -d "${TMPDIR:-/tmp}/bcd-clips.XXXXXX")"
trap 'rm -rf "$T"' EXIT

python3 "$R/tools/video-test-clips/genframes.py" "$T/src"

echo "== test.mp4 (AVAssetWriter: H.264 Baseline + AAC-LC) =="
swiftc -O "$R/tools/video-test-clips/mkmp4.swift" -o "$T/mkmp4"
"$T/mkmp4" "$T/src/frames.bgra" "$T/src/tone.pcm" "$T/test.mp4" 160 96 30 15 44100

echo "== test.wmv (FFmpeg wmv2 + wmav2 in ASF) =="
FF="${FFMPEG:-}"
if [ -z "$FF" ]; then
    TAR="$R/build/ffmpeg/src/ffmpeg-7.1.1.tar.xz"
    WANT="$(awk '{print $1}' "$R/build/ffmpeg/src/SHA256SUMS")"
    [ "$(shasum -a 256 "$TAR" | awk '{print $1}')" = "$WANT" ] || { echo "the tracked FFmpeg tarball does not match build/ffmpeg/src/SHA256SUMS" >&2; exit 1; }
    mkdir -p "$T/ff/build"
    tar -xf "$TAR" -C "$T/ff"
    (cd "$T/ff/build" && ../ffmpeg-7.1.1/configure --disable-everything --disable-gpl --disable-nonfree --disable-version3 --disable-autodetect \
        --disable-doc --disable-network --disable-ffplay --disable-ffprobe --enable-ffmpeg --disable-x86asm --enable-small \
        --enable-encoder=wmv2,wmav2 --enable-decoder=rawvideo,pcm_s16le --enable-demuxer=rawvideo,pcm_s16le --enable-muxer=asf \
        --enable-protocol=file --enable-filter=scale,format,aresample,anull,null >/dev/null && nice -n 10 make -j3 >/dev/null 2>&1)
    FF="$T/ff/build/ffmpeg"
fi
"$FF" -hide_banner -loglevel warning -y -f rawvideo -pix_fmt bgra -s 160x96 -r 15 -i "$T/src/frames.bgra" \
    -f s16le -ar 44100 -ac 1 -i "$T/src/tone.pcm" -c:v wmv2 -b:v 250k -g 15 -pix_fmt yuv420p -c:a wmav2 -b:a 48k \
    -map 0:v -map 1:a -bitexact -fflags +bitexact "$T/test.wmv"

mkdir -p "$R/tests/dxtests/clips"
cp "$T/test.mp4" "$T/test.wmv" "$R/tests/dxtests/clips/"
python3 - "$R" <<'PY'
import hashlib, sys
from pathlib import Path
R = Path(sys.argv[1])
out = ["// SPDX-License-Identifier: GPL-3.0-only",
       "// Copyright 2026 thebcd69 (BCD)",
       "// BCD Material: additional terms under GPL-3.0 section 7 apply; see LICENSE-BCD.md.",
       "//",
       "// Generated by tools/gen-video-test-clips.sh from tests/dxtests/clips/test.mp4 and test.wmv. Do not edit."]
for name in ("mp4", "wmv"):
    data = (R / "tests/dxtests/clips" / ("test." + name)).read_bytes()
    out.append("// clip-%s-sha256: %s" % (name, hashlib.sha256(data).hexdigest()))
for name in ("mp4", "wmv"):
    data = (R / "tests/dxtests/clips" / ("test." + name)).read_bytes()
    out.append("")
    out.append("static const unsigned char clip_%s[] = {" % name)
    for i in range(0, len(data), 12):
        out.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    out.append("};")
(R / "tests/dxtests/video_clips.h").write_text("\n".join(out) + "\n")
print("video_clips.h written")
PY
echo "done: tests/dxtests/clips/test.mp4, test.wmv, tests/dxtests/video_clips.h"
